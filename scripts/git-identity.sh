#!/usr/bin/env bash
#
# Write ~/.gitconfig.local with your git identity.
#
# Kept out of the repo on purpose: home/.gitconfig `[include]`s this file, so
# the committed config carries settings and aliases but no personal details.

set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

TARGET="$HOME/.gitconfig.local"

if [ -e "$TARGET" ]; then
  info "$(tilde "$TARGET") already exists:"
  git config --file "$TARGET" --list | sed 's/^/  /'
  read -r -p "Overwrite it? [y/N] " reply
  case "$reply" in
    [yY]*) ;;
    *) skip "left alone"; exit 0 ;;
  esac
fi

current_name="$(git config --global user.name 2>/dev/null || true)"
current_email="$(git config --global user.email 2>/dev/null || true)"

# The machine this repo came from had GitHub's literal documentation
# placeholder sitting in ~/.gitconfig. Don't offer it back as a default.
case "$current_email" in
  ID+username@users.noreply.github.com) current_email="" ;;
esac

read -r -p "Git user.name${current_name:+ [$current_name]}: " name
name="${name:-$current_name}"
[ -n "$name" ] || die "a name is required"

printf 'Git user.email — for a private address use the form\n'
printf '  12345678+yourusername@users.noreply.github.com\n'
printf '(find the number at https://github.com/settings/emails)\n'
read -r -p "Git user.email${current_email:+ [$current_email]}: " email
email="${email:-$current_email}"
[ -n "$email" ] || die "an email is required"

case "$email" in
  *ID+username*) die "that's still the placeholder — substitute your real ID and username" ;;
  *@*) ;;
  *) die "'$email' doesn't look like an email address" ;;
esac

cat > "$TARGET" <<EOF
# Generated by scripts/git-identity.sh. Not committed.
[user]
	name = $name
	email = $email
EOF

ok "wrote $(tilde "$TARGET")"
git config --file "$TARGET" --list | sed 's/^/  /'
